import { afterAll, afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

// config.js 在 import 时即执行 loadConfig()（含密钥解析副作用）。为避免测试
// 在 server/data 下生成密钥文件，先通过 env 提供显式值再动态 import。
process.env.ALLOW_INSECURE_NO_AUTH = '1';
process.env.ENCRYPTION_KEY = 'f'.repeat(64);
process.env.API_SECRET = 'import-time-placeholder';

const { isInsecureNoAuthEnabled, resolveApiSecret, resolveEncryptionKey } = await import('../../src/config.js');

const ENV_KEYS = ['API_SECRET', 'ALLOW_INSECURE_NO_AUTH', 'ENCRYPTION_KEY'] as const;
let savedEnv: Record<string, string | undefined> = {};

beforeEach(() => {
  savedEnv = {};
  for (const key of ENV_KEYS) {
    savedEnv[key] = process.env[key];
    delete process.env[key];
  }
});

afterEach(() => {
  for (const key of ENV_KEYS) {
    if (savedEnv[key] === undefined) delete process.env[key];
    else process.env[key] = savedEnv[key];
  }
});

function tmpDir(): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gsm-api-secret-'));
  return dir;
}

const cleanupDirs: string[] = [];
afterAll(() => {
  for (const dir of cleanupDirs) fs.rmSync(dir, { recursive: true, force: true });
});

describe('isInsecureNoAuthEnabled', () => {
  it.each(['1', 'true', 'TRUE', 'True', ' 1 ', ' true '])('treats %j as enabled', (value) => {
    expect(isInsecureNoAuthEnabled(value)).toBe(true);
  });

  it.each(['0', 'false', 'FALSE', 'yes', 'on', '', '  ', undefined])('treats %j as disabled', (value) => {
    expect(isInsecureNoAuthEnabled(value)).toBe(false);
  });
});

describe('resolveApiSecret', () => {
  it('uses a non-blank API_SECRET env value unchanged (whitespace is significant), without touching the data dir', () => {
    const dir = tmpDir();
    cleanupDirs.push(dir);
    process.env.API_SECRET = '  env-secret  ';
    expect(resolveApiSecret(dir)).toEqual({ secret: '  env-secret  ', source: 'env' });
    expect(fs.readdirSync(dir)).toEqual([]);
  });

  it('treats a blank API_SECRET env value as unset', () => {
    const dir = tmpDir();
    cleanupDirs.push(dir);
    process.env.API_SECRET = '   ';
    const resolved = resolveApiSecret(dir);
    expect(resolved.secret).toBeTruthy();
    expect(resolved.source).toBe('generated');
    expect(fs.existsSync(path.join(dir, '.api-secret'))).toBe(true);
  });

  it('returns null (dev mode, no file) when ALLOW_INSECURE_NO_AUTH is enabled', () => {
    const dir = tmpDir();
    cleanupDirs.push(dir);
    process.env.ALLOW_INSECURE_NO_AUTH = '1';
    expect(resolveApiSecret(dir)).toEqual({ secret: null, source: null });
    expect(fs.existsSync(path.join(dir, '.api-secret'))).toBe(false);
  });

  it('generates a persistent secret with mode 0600 and logs a loud banner on first start', () => {
    const dir = tmpDir();
    cleanupDirs.push(dir);
    const warnSpy = vi.spyOn(console, 'warn').mockImplementation(() => {});
    try {
      const resolved = resolveApiSecret(dir);
      expect(resolved.secret).toMatch(/^[0-9a-f]{64}$/);
      expect(resolved.source).toBe('generated');

      const secretPath = path.join(dir, '.api-secret');
      expect(fs.readFileSync(secretPath, 'utf-8')).toBe(resolved.secret);
      if (process.platform !== 'win32') {
        // Windows 不报告 POSIX 权限位（观察到为 0o666），只断言文件已生成。
        expect(fs.statSync(secretPath).mode & 0o777).toBe(0o600);
      } else {
        expect(fs.existsSync(secretPath)).toBe(true);
      }

      const banner = warnSpy.mock.calls.map((call) => call.join(' ')).join('\n');
      expect(banner).toContain('.api-secret');
      // 取回指引只指向数据卷文件（密钥值不写入日志），不得再指向 docker logs。
      expect(banner).toContain('docker compose exec backend');
      expect(banner).not.toContain('logs backend');
      expect(banner).toContain('API Secret');
    } finally {
      warnSpy.mockRestore();
    }
  });

  it('reuses the same secret across restarts (read-before-write)', () => {
    const dir = tmpDir();
    cleanupDirs.push(dir);
    const first = resolveApiSecret(dir);
    const second = resolveApiSecret(dir); // simulate a restart on the same dataDir
    expect(second).toEqual(first);
    expect(fs.readFileSync(path.join(dir, '.api-secret'), 'utf-8')).toBe(first.secret);
    // 原子发布（临时文件 + link）不得在数据目录残留 .tmp 文件。
    expect(fs.readdirSync(dir).filter((f) => f.includes('.tmp'))).toEqual([]);
  });

  it('never overwrites an existing .api-secret even with different generated bytes', () => {
    const dir = tmpDir();
    cleanupDirs.push(dir);
    const secretPath = path.join(dir, '.api-secret');
    fs.writeFileSync(secretPath, 'existing-persisted-secret', { mode: 0o600 });
    const statBefore = fs.statSync(secretPath);

    vi.spyOn(console, 'warn').mockImplementation(() => {});
    try {
      expect(resolveApiSecret(dir)).toEqual({ secret: 'existing-persisted-secret', source: 'generated' });
    } finally {
      vi.restoreAllMocks();
    }
    expect(fs.readFileSync(secretPath, 'utf-8')).toBe('existing-persisted-secret');
    expect(fs.statSync(secretPath).mtimeMs).toBe(statBefore.mtimeMs);
  });

  it('falls back to an ephemeral secret (no crash) when the existing file is empty', () => {
    const dir = tmpDir();
    cleanupDirs.push(dir);
    const secretPath = path.join(dir, '.api-secret');
    fs.writeFileSync(secretPath, '   \n', { mode: 0o600 });
    const errorSpy = vi.spyOn(console, 'error').mockImplementation(() => {});
    try {
      const resolved = resolveApiSecret(dir);
      expect(resolved.secret).toMatch(/^[0-9a-f]{64}$/);
      expect(resolved.source).toBe('generated');
      expect(errorSpy.mock.calls.some((call) => String(call[0]).includes('empty'))).toBe(true);
    } finally {
      errorSpy.mockRestore();
    }
    // The broken file is left untouched for the operator to fix.
    expect(fs.readFileSync(secretPath, 'utf-8')).toBe('   \n');
  });

  it('falls back to reading the concurrent winner on EEXIST without overwriting it', () => {
    const dir = tmpDir();
    cleanupDirs.push(dir);
    const secretPath = path.join(dir, '.api-secret');
    fs.writeFileSync(secretPath, 'race-winner-secret', { mode: 0o600 });

    // Simulate the race: existsSync misses the file, the atomic publish (link)
    // loses with EEXIST — the concurrent winner's secret must be used as-is.
    const existsSpy = vi.spyOn(fs, 'existsSync').mockReturnValue(false);
    const linkSpy = vi.spyOn(fs, 'linkSync').mockImplementation(() => {
      throw Object.assign(new Error('file already exists'), { code: 'EEXIST' });
    });
    try {
      expect(resolveApiSecret(dir)).toEqual({ secret: 'race-winner-secret', source: 'generated' });
    } finally {
      existsSpy.mockRestore();
      linkSpy.mockRestore();
    }
    expect(fs.readFileSync(secretPath, 'utf-8')).toBe('race-winner-secret');
    // The losing process must not leave temp files behind.
    expect(fs.readdirSync(dir).filter((f) => f.includes('.tmp'))).toEqual([]);
  });

  it('falls back to an ephemeral secret (no crash-loop) when the data dir is not writable', () => {
    if (process.platform === 'win32') {
      return; // Windows 没有 getuid，且 chmod 不阻止对目录写入，场景不成立
    }
    if (typeof process.getuid === 'function' && process.getuid() === 0) {
      return; // root ignores directory permissions
    }
    const dir = tmpDir();
    cleanupDirs.push(dir);
    fs.chmodSync(dir, 0o500); // read + execute, no write
    const errorSpy = vi.spyOn(console, 'error').mockImplementation(() => {});
    try {
      const resolved = resolveApiSecret(dir);
      expect(resolved.secret).toMatch(/^[0-9a-f]{64}$/);
      expect(resolved.source).toBe('generated');
      const errors = errorSpy.mock.calls.map((call) => call.join(' ')).join('\n');
      expect(errors).toContain('.api-secret');
    } finally {
      errorSpy.mockRestore();
      fs.chmodSync(dir, 0o700);
    }
    expect(fs.existsSync(path.join(dir, '.api-secret'))).toBe(false);
  });
});

describe('resolveEncryptionKey', () => {
  it('reuses an existing .encryption-key and never regenerates it', () => {
    const dir = tmpDir();
    cleanupDirs.push(dir);
    const keyPath = path.join(dir, '.encryption-key');
    const existing = crypto.randomBytes(32).toString('hex');
    fs.writeFileSync(keyPath, existing, { mode: 0o600 });
    const statBefore = fs.statSync(keyPath);

    expect(resolveEncryptionKey(dir)).toBe(existing);
    expect(fs.readFileSync(keyPath, 'utf-8').trim()).toBe(existing);
    expect(fs.statSync(keyPath).mtimeMs).toBe(statBefore.mtimeMs);
  });

  it('logs a loud backup warning when auto-generating a new .encryption-key', () => {
    const dir = tmpDir();
    cleanupDirs.push(dir);
    const warnSpy = vi.spyOn(console, 'warn').mockImplementation(() => {});
    try {
      const key = resolveEncryptionKey(dir);
      expect(key).toMatch(/^[0-9a-f]{64}$/);
      const warnings = warnSpy.mock.calls.map((call) => call.join(' ')).join('\n');
      expect(warnings).toContain('.encryption-key');
      expect(warnings).toMatch(/[Bb]ackup/);
      expect(warnings).toContain('volume');
    } finally {
      warnSpy.mockRestore();
    }
    expect(fs.existsSync(path.join(dir, '.encryption-key'))).toBe(true);
  });

  it('does not log the backup warning when the key comes from ENCRYPTION_KEY env', () => {
    const dir = tmpDir();
    cleanupDirs.push(dir);
    process.env.ENCRYPTION_KEY = 'a'.repeat(64);
    const warnSpy = vi.spyOn(console, 'warn').mockImplementation(() => {});
    try {
      expect(resolveEncryptionKey(dir)).toBe('a'.repeat(64));
      expect(warnSpy).not.toHaveBeenCalled();
    } finally {
      warnSpy.mockRestore();
    }
    expect(fs.existsSync(path.join(dir, '.encryption-key'))).toBe(false);
  });
});
